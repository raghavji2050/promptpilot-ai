# Regenerates supabase/migrations/*.sql and supabase/PASTE_ME_pending.sql from the loose files in supabase/. Usage: python3 scripts/gen-migrations.py
import re,os
import pathlib
S=str(pathlib.Path(__file__).resolve().parent.parent/'supabase')+'/'
M=S+'migrations/'
def idem(sql):
    out=[]
    for line in sql.split('\n'):
        m=re.match(r'^create policy\s+("[^"]+"|\S+)\s+on\s+(\S+)',line)
        if m and not (out and out[-1].startswith('drop policy if exists')): out.append(f'drop policy if exists {m.group(1)} on {m.group(2)};')
        m=re.match(r'^create trigger\s+(\S+)\s+.*?\bon\s+(\S+)',line)
        if m and not (out and out[-1].startswith('drop trigger if exists')): out.append(f'drop trigger if exists {m.group(1)} on {m.group(2)};')
        out.append(line)
    return '\n'.join(out)
files=[('0001_schema.sql','schema.sql','Core schema: enums, tables, RLS policies, functions, targets seed.'),
 ('0002_fix_function_grants.sql','fix-function-grants.sql','Revoke anon EXECUTE on auth-only functions.'),
 ('0003_festivals.sql','festivals.sql','Optional admin festival date overrides (public read).'),
 ('0004_run_quota.sql','run-quota.sql','Run quota + daily API rate-limit caps (consume_run_quota).'),
 ('0005_pro_waitlist.sql','pro-waitlist.sql','Pro waitlist (insert-only).'),
 ('0006_builder_share.sql','builder-share.sql','Short builder share links (/s/q12345678).'),
 ('0007_seed_library.sql','seed-library.sql','Seed: 10 categories + library items and bodies (upserts).')]
paste=["-- PromptPilot: PASTE ME — everything still pending in Supabase (generated by scripts/gen-migrations.py from supabase/migrations/0002-0007).",
"-- Supabase dashboard → SQL Editor → New query → paste this WHOLE file → Run. Idempotent: safe to re-run.",
"-- Assumes 0001_schema.sql is already applied (live site reads library_items fine). If not, run migrations/0001_schema.sql first.",
"-- After running: /api/keep-alive count > 0, favorites work, rate-limit daily caps become shared once SUPABASE_SERVICE_ROLE_KEY is set in Vercel.",""]
for i,(dst,src,desc) in enumerate(files):
    body=open(S+src).read().rstrip('\n')
    body=idem(body)
    hdr=f'-- Migration {dst} (from supabase/{src}). {desc}\n-- Idempotent: safe to re-run. Run migrations in numeric order in the Supabase SQL editor.\n'
    open(M+dst,'w').write(hdr+body+'\n')
    if i>0: paste+= [f'-- ===== {dst} =====', body, '']
open(S+'PASTE_ME_pending.sql','w').write('\n'.join(paste))
