/**
 * Generates ../seed-library.sql from src/content so DB rows (needed for favorites,
 * copy counts) match the static library. Idempotent: upserts by slug.
 * Run: npx tsx scripts/gen-library-seed.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ALL_PROMPTS } from "../src/content/index";
import { CATEGORIES } from "../src/lib/categories/index";

const q = (s: string | undefined | null) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[] | undefined) => `array[${(a ?? []).map(q).join(",")}]::text[]`;

const rows = ALL_PROMPTS.map((p) =>
  `(${q(p.slug)}, ${q(p.kind)}::public.library_kind, ${q(p.title)}, ${q(p.summary.slice(0, 400))}, ${q(p.failureMode)}, ${arr(p.targets)}, ${arr(p.stacks)}, ${arr(p.tags)}, ${q(p.locale ?? "en")}, ${q(p.aspect)}, ${p.requiresPhoto ? "true" : "false"}, 'published'::public.content_status, ${q(p.trend?.lastVerified ?? null)}::date)`,
);
const cats = CATEGORIES.map((c, i) => `(${q(c.id)}, ${q(c.name)}, ${q(c.id === "coding" ? "developer" : "general")}::public.library_kind, ${q(c.description)}, ${(i + 1) * 10})`);
const catLinks = ALL_PROMPTS.map((p) => `(${q(p.slug)}, ${q(p.cat ?? null)})`);
const bodies = ALL_PROMPTS.map((p) => `(${q(p.slug)}, ${q(p.body)})`);

const sql = `-- Generated by app/scripts/gen-library-seed.ts. Do not edit by hand.
-- Upserts ${CATEGORIES.length} goal categories and ${ALL_PROMPTS.length} library items + bodies so favorites can reference them.
begin;
insert into public.categories (slug, name, kind, description, sort_order)
values
${cats.join(",\n")}
on conflict (slug) do update set name = excluded.name, kind = excluded.kind, description = excluded.description, sort_order = excluded.sort_order;

insert into public.library_items (slug, kind, title, summary, failure_mode, targets, stacks, tags, locale, aspect_ratio, requires_photo, status, last_verified)
values
${rows.join(",\n")}
on conflict (slug) do update set kind = excluded.kind, title = excluded.title, summary = excluded.summary,
  failure_mode = excluded.failure_mode, targets = excluded.targets, stacks = excluded.stacks, tags = excluded.tags,
  locale = excluded.locale, aspect_ratio = excluded.aspect_ratio, requires_photo = excluded.requires_photo,
  status = excluded.status, last_verified = excluded.last_verified;

insert into public.library_item_bodies (item_id, body)
select li.id, v.body from (values
${bodies.join(",\n")}
) as v(slug, body) join public.library_items li on li.slug = v.slug
on conflict (item_id) do update set body = excluded.body;

update public.library_items li set category_id = c.id
from (values
${catLinks.join(",\n")}
) as v(slug, cat) join public.categories c on c.slug = v.cat
where li.slug = v.slug;
commit;
`;
const out = join(__dirname, "..", "supabase", "seed-library.sql");
writeFileSync(out, sql);
console.log(`wrote ${out} (${ALL_PROMPTS.length} items)`);
