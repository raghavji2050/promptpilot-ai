/**
 * Day 7b: export a built prompt as an Agent Skill (SKILL.md) and as copy-ready snippets
 * for ChatGPT, Claude and Cursor. Day 12 suggestion: also standing Custom Instructions /
 * Claude Project Instructions (portable personalization text, not a one-shot task paste).
 * Pure functions, no network.
 */

export const SKILL_NAME_MAX = 64;
export const SKILL_DESCRIPTION_MAX = 1024;
const FALLBACK_NAME = "promptpilot-prompt";

/** Lowercase letters, digits and single hyphens (Agent Skills naming rule), max 64 chars. */
export function toSkillName(title: string): string {
  const slug = title
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  const cut = slug.slice(0, SKILL_NAME_MAX).replace(/-+$/g, "");
  return cut || FALLBACK_NAME;
}

/** One-line YAML double-quoted scalar. JSON string syntax is valid YAML, so JSON.stringify escapes quotes, backslashes and control chars. */
export function yamlString(value: string, max = SKILL_DESCRIPTION_MAX): string {
  let s = value.replace(/\s+/g, " ").trim();
  if (s.length > max) s = `${s.slice(0, max - 1).trimEnd()}…`;
  return JSON.stringify(s);
}

export function skillDescription(goal: string): string {
  const g = goal.replace(/\s+/g, " ").trim().replace(/[.\s]+$/, "");
  return g ? `Use when the user wants to: ${g}. Prompt generated by PromptPilot.` : "Reusable prompt generated by PromptPilot.";
}

export interface SkillInput { title: string; goal?: string; body: string }

/** A valid SKILL.md: YAML frontmatter (name, description) then the prompt as the skill instructions. */
export function buildSkillMd({ title, goal, body }: SkillInput): string {
  const name = toSkillName(title);
  const heading = title.replace(/\s+/g, " ").trim() || "PromptPilot prompt";
  return [
    "---",
    `name: ${name}`,
    `description: ${yamlString(skillDescription(goal ?? title))}`,
    "---",
    "",
    `# ${heading}`,
    "",
    body.trim(),
    "",
  ].join("\n");
}

export type SnippetTarget = "chatgpt" | "claude" | "cursor" | "chatgpt-custom" | "claude-project" | "gemini" | "perplexity";

export const SNIPPET_TARGETS: { id: SnippetTarget; name: string; help: string }[] = [
  { id: "chatgpt", name: "ChatGPT", help: "Paste into a new ChatGPT chat, or into a custom GPT's instructions." },
  { id: "claude", name: "Claude", help: "Paste into a Claude chat or a Project's instructions. The XML tags help Claude separate instructions from your follow-ups." },
  { id: "cursor", name: "Cursor", help: "Save as a project rule file (path below), or paste the part after the second --- into Cursor chat." },
  { id: "chatgpt-custom", name: "ChatGPT Custom Instructions", help: "Standing instructions for ChatGPT Settings → Custom instructions (\"How would you like ChatGPT to respond?\"). Applies to all chats; Free/Go ≤1,500 chars, Plus+ ≤5,000." },
  { id: "claude-project", name: "Claude Project Instructions", help: "Standing project instructions for Claude Projects (apply only inside that project). Free users can have up to 5 projects." },
  { id: "gemini", name: "Gemini skill", help: "Paste into a Gemini skill's (or Gem's) name, description and instructions fields, or upload the SKILL.md above: Gemini can import SKILL.md files on the web app and Mac app. Google says Gems become read-only on 17 Nov 2026 and are recreated as skills." },
  { id: "perplexity", name: "Perplexity Project", help: "Paste each field into a Perplexity Project (title ≤50 chars, description ≤1,000, instructions ≤8,000 in Settings → Context). Longer text is trimmed to fit; counts are shown above the instructions." },
];

export function chatgptSnippet(body: string): string {
  return body.trim();
}

export function claudeSnippet(body: string): string {
  return `<instructions>\n${body.trim()}\n</instructions>\n\nFollow the instructions above. If key details are missing, ask me before answering.`;
}

export function cursorRulePath(title: string): string {
  return `.cursor/rules/${toSkillName(title)}.mdc`;
}

/** Cursor project rule (.mdc): description frontmatter, applied when relevant (not always). */
export function cursorSnippet(body: string, title: string, goal?: string): string {
  return [
    "---",
    `description: ${yamlString(skillDescription(goal ?? title))}`,
    "alwaysApply: false",
    "---",
    "",
    body.trim(),
    "",
  ].join("\n");
}

/**
 * Standing ChatGPT Custom Instructions text (not a one-shot task paste).
 * Tuned for the "How would you like ChatGPT to respond?" field.
 */
export function chatgptCustomInstructions(body: string, title: string, goal?: string): string {
  const focus = (goal ?? title).replace(/\s+/g, " ").trim() || "my work";
  return [
    `When helping with tasks related to "${focus}", follow these standing instructions:`,
    "",
    body.trim(),
    "",
    "Always ask clarifying questions when key details are missing. Do not invent facts, numbers, citations, or experience. Leave [placeholders] for anything I must fill in.",
  ].join("\n");
}

/**
 * Standing Claude Project Instructions (apply only within a Claude Project).
 */
export function claudeProjectInstructions(body: string, title: string, goal?: string): string {
  const focus = title.replace(/\s+/g, " ").trim() || "Project";
  const g = (goal ?? "").replace(/\s+/g, " ").trim();
  return [
    `Project focus: ${focus}${g && g !== focus ? ` (${g})` : ""}`,
    "",
    "Standing instructions for this project:",
    "",
    body.trim(),
    "",
    "If key details are missing, ask before answering. Never invent facts, numbers, or citations. Use [placeholders] for anything the user must supply.",
  ].join("\n");
}

/** Gemini skill / Gem fields: name, one-line description, instructions (same fields Gemini asks for). */
export function geminiSkillInstructions(body: string, title: string, goal?: string): string {
  const name = title.replace(/\s+/g, " ").trim() || "My prompt";
  return [
    `Name: ${name}`,
    `Description: ${skillDescription(goal ?? title)}`,
    "",
    "Instructions:",
    body.trim(),
    "",
    "If key details are missing, ask me before answering. Never invent facts, numbers, or citations. Leave [placeholders] for anything I must fill in.",
  ].join("\n");
}

export const PERPLEXITY_TITLE_MAX = 50;
export const PERPLEXITY_DESCRIPTION_MAX = 1000;
export const PERPLEXITY_INSTRUCTIONS_MAX = 8000;

function fit(value: string, max: number): string {
  return value.length > max ? `${value.slice(0, max - 1).trimEnd()}…` : value;
}

/** Perplexity Project fields, trimmed to Perplexity's documented limits (title 50, description 1,000, instructions 8,000). */
export function perplexityProjectFields(body: string, title: string, goal?: string): { title: string; description: string; instructions: string } {
  const t = fit(title.replace(/\s+/g, " ").trim() || "My prompt", PERPLEXITY_TITLE_MAX);
  const description = fit(skillDescription(goal ?? title), PERPLEXITY_DESCRIPTION_MAX);
  const instructions = fit(
    `${body.trim()}\n\nIf key details are missing, ask me before answering. Cite sources for factual claims. Never invent facts, numbers, or citations. Leave [placeholders] for anything I must fill in.`,
    PERPLEXITY_INSTRUCTIONS_MAX,
  );
  return { title: t, description, instructions };
}

export function perplexityProjectInstructions(body: string, title: string, goal?: string): string {
  const f = perplexityProjectFields(body, title, goal);
  return [
    `Title: ${f.title}`,
    `Description: ${f.description}`,
    "",
    `Instructions (${f.instructions.length}/${PERPLEXITY_INSTRUCTIONS_MAX} chars):`,
    f.instructions,
  ].join("\n");
}

export function buildSnippet(target: SnippetTarget, body: string, title: string, goal?: string): string {
  if (target === "claude") return claudeSnippet(body);
  if (target === "cursor") return cursorSnippet(body, title, goal);
  if (target === "chatgpt-custom") return chatgptCustomInstructions(body, title, goal);
  if (target === "claude-project") return claudeProjectInstructions(body, title, goal);
  if (target === "gemini") return geminiSkillInstructions(body, title, goal);
  if (target === "perplexity") return perplexityProjectInstructions(body, title, goal);
  return chatgptSnippet(body);
}
