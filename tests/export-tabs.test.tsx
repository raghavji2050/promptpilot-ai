// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from "vitest";
import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import { ExportTabs } from "@/components/ExportTabs";
import { ToastProvider } from "@/components/ui/Toast";

afterEach(() => { cleanup(); vi.restoreAllMocks(); });
const ui = () => render(<ToastProvider><ExportTabs text="Do the thing." title="Fix my bug" goal="Fix my bug" /></ToastProvider>);

describe("<ExportTabs>", () => {
  it("renders an accessible tablist and switches with click and arrow keys", () => {
    ui();
    const tabs = screen.getAllByRole("tab");
    expect(tabs.map((t) => t.textContent)).toEqual(["ChatGPT", "Claude", "Cursor", "ChatGPT Custom Instructions", "Claude Project Instructions", "Gemini skill", "Perplexity Project"]);
    expect(tabs[0]!.getAttribute("aria-selected")).toBe("true");
    expect(screen.getByRole("tabpanel").getAttribute("aria-labelledby")).toBe(tabs[0]!.id);
    fireEvent.click(tabs[1]!);
    expect(screen.getByLabelText("Claude snippet").textContent).toContain("<instructions>");
    fireEvent.keyDown(screen.getAllByRole("tab")[1]!, { key: "ArrowRight" });
    expect(screen.getAllByRole("tab")[2]!.getAttribute("aria-selected")).toBe("true");
    expect(screen.getByText(".cursor/rules/fix-my-bug.mdc")).toBeTruthy();
  });

  it("copies the active snippet", async () => {
    const writeText = vi.fn(() => Promise.resolve());
    Object.defineProperty(navigator, "clipboard", { value: { writeText }, configurable: true });
    ui();
    fireEvent.click(screen.getByRole("tab", { name: /^Claude$/ }));
    await act(async () => { fireEvent.click(screen.getByRole("button", { name: /^Copy for Claude$/ })); await Promise.resolve(); });
    expect(writeText).toHaveBeenCalledWith(expect.stringContaining("<instructions>\nDo the thing.\n</instructions>"));
  });

  it("downloads SKILL.md", async () => {
    let blob: Blob | undefined;
    Object.assign(URL, { createObjectURL: vi.fn((b: Blob) => { blob = b; return "blob:x"; }), revokeObjectURL: vi.fn() });
    const click = vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(() => {});
    ui();
    fireEvent.click(screen.getByRole("button", { name: /Export as SKILL\.md/ }));
    expect(click).toHaveBeenCalled();
    const md = await blob!.text();
    expect(md.startsWith("---\nname: fix-my-bug\ndescription: \"Use when the user wants to: Fix my bug. Prompt generated by PromptPilot.\"\n---\n")).toBe(true);
    expect(md).toContain("Do the thing.");
  });

  it("shows standing Custom Instructions and Project Instructions snippets", () => {
    ui();
    fireEvent.click(screen.getByRole("tab", { name: "ChatGPT Custom Instructions" }));
    expect(screen.getByLabelText("ChatGPT Custom Instructions snippet").textContent).toContain("standing instructions");
    fireEvent.click(screen.getByRole("tab", { name: "Claude Project Instructions" }));
    expect(screen.getByLabelText("Claude Project Instructions snippet").textContent).toContain("Project focus:");
  });
});
