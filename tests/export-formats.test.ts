import { describe, expect, it } from "vitest";
import { buildSkillMd, buildSnippet, chatgptSnippet, claudeSnippet, chatgptCustomInstructions, claudeProjectInstructions, geminiSkillInstructions, perplexityProjectFields, perplexityProjectInstructions, cursorRulePath, cursorSnippet, skillDescription, toSkillName, yamlString, SKILL_NAME_MAX } from "@/lib/export-formats";

/** Minimal frontmatter parser for one-line `key: value` pairs; double-quoted values parsed as JSON (valid YAML subset). */
function frontmatter(md: string): { fm: Record<string, string>; body: string } {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(md);
  if (!m) throw new Error("no frontmatter");
  const fm: Record<string, string> = {};
  for (const line of m[1]!.split("\n")) {
    const i = line.indexOf(": ");
    const k = line.slice(0, i); const v = line.slice(i + 2);
    fm[k] = v.startsWith("\"") ? (JSON.parse(v) as string) : v;
  }
  return { fm, body: m[2]! };
}

describe("toSkillName", () => {
  it("kebab-cases titles", () => {
    expect(toSkillName("Write a Cover Letter for a Senior Laravel job!")).toBe("write-a-cover-letter-for-a-senior-laravel-job");
    expect(toSkillName("  Café   déjà vu  ")).toBe("cafe-deja-vu");
  });
  it("caps length without trailing hyphen and falls back when empty", () => {
    const n = toSkillName("a ".repeat(100));
    expect(n.length).toBeLessThanOrEqual(SKILL_NAME_MAX);
    expect(n).toMatch(/^[a-z0-9]+(-[a-z0-9]+)*$/);
    expect(toSkillName("दिवाली पोस्ट")).toBe("promptpilot-prompt");
    expect(toSkillName("---")).toBe("promptpilot-prompt");
  });
});

describe("yamlString", () => {
  it("escapes quotes, backslashes, colons and newlines on one line", () => {
    const s = yamlString('He said: "hi" \\ there\n# not a comment');
    expect(s).not.toContain("\n");
    expect(JSON.parse(s)).toBe('He said: "hi" \\ there # not a comment');
  });
  it("truncates long values", () => {
    expect((JSON.parse(yamlString("x".repeat(2000))) as string).length).toBeLessThanOrEqual(1024);
  });
});

describe("buildSkillMd", () => {
  const md = buildSkillMd({ title: "Grow my Instagram: \"reels\"", goal: "Grow my Instagram: \"reels\"\n--- injected", body: "You are a coach.\n\n---\nDo X." });
  it("has valid name + description frontmatter and the prompt body", () => {
    const { fm, body } = frontmatter(md);
    expect(Object.keys(fm)).toEqual(["name", "description"]);
    expect(fm.name).toBe("grow-my-instagram-reels");
    expect(fm.description).toBe('Use when the user wants to: Grow my Instagram: "reels" --- injected. Prompt generated by PromptPilot.');
    expect(body).toContain("# Grow my Instagram: \"reels\"");
    expect(body).toContain("You are a coach.\n\n---\nDo X.");
  });
  it("frontmatter cannot be broken by user text", () => {
    expect(md.split("\n").slice(0, 4).filter((l) => l === "---")).toHaveLength(2);
  });
  it("description fallback", () => {
    expect(skillDescription("   ")).toBe("Reusable prompt generated by PromptPilot.");
  });
});

describe("snippets", () => {
  const body = "  Act as a Laravel expert.\nFix the bug.  ";
  it("ChatGPT is the plain prompt", () => {
    expect(chatgptSnippet(body)).toBe("Act as a Laravel expert.\nFix the bug.");
    expect(buildSnippet("chatgpt", body, "t")).toBe(chatgptSnippet(body));
  });
  it("Claude wraps in <instructions> tags", () => {
    const s = claudeSnippet(body);
    expect(s.startsWith("<instructions>\nAct as a Laravel expert.\nFix the bug.\n</instructions>")).toBe(true);
    expect(buildSnippet("claude", body, "t")).toBe(s);
  });
  it("Cursor is an .mdc rule with description + alwaysApply false", () => {
    const s = cursorSnippet(body, "Fix Laravel bug", "Fix Laravel bug");
    const { fm, body: b } = frontmatter(s);
    expect(fm).toEqual({ description: "Use when the user wants to: Fix Laravel bug. Prompt generated by PromptPilot.", alwaysApply: "false" });
    expect(b.trim()).toBe("Act as a Laravel expert.\nFix the bug.");
    expect(cursorRulePath("Fix Laravel bug")).toBe(".cursor/rules/fix-laravel-bug.mdc");
    expect(buildSnippet("cursor", body, "Fix Laravel bug", "Fix Laravel bug")).toBe(s);
  });
  it("ChatGPT Custom Instructions is standing personalization text", () => {
    const s = chatgptCustomInstructions(body, "Fix Laravel bug", "Fix Laravel bug");
    expect(s).toContain('When helping with tasks related to "Fix Laravel bug"');
    expect(s).toContain("Act as a Laravel expert.\nFix the bug.");
    expect(s).toContain("standing instructions");
    expect(buildSnippet("chatgpt-custom", body, "Fix Laravel bug", "Fix Laravel bug")).toBe(s);
  });
  it("Claude Project Instructions is standing project text", () => {
    const s = claudeProjectInstructions(body, "Fix Laravel bug", "Fix Laravel bug");
    expect(s.startsWith("Project focus: Fix Laravel bug")).toBe(true);
    expect(s).toContain("Standing instructions for this project:");
    expect(s).toContain("Act as a Laravel expert.\nFix the bug.");
    expect(buildSnippet("claude-project", body, "Fix Laravel bug", "Fix Laravel bug")).toBe(s);
  });
  it("Gemini skill gives name, description and instructions fields", () => {
    const s = geminiSkillInstructions(body, "Fix Laravel bug", "Fix Laravel bug");
    expect(s.startsWith("Name: Fix Laravel bug\nDescription: Use when the user wants to: Fix Laravel bug.")).toBe(true);
    expect(s).toContain("Instructions:\nAct as a Laravel expert.\nFix the bug.");
    expect(buildSnippet("gemini", body, "Fix Laravel bug", "Fix Laravel bug")).toBe(s);
    expect(geminiSkillInstructions(body, "  ")).toContain("Name: My prompt");
  });
  it("Perplexity Project fields respect title/description/instructions limits", () => {
    const s = perplexityProjectInstructions(body, "Fix Laravel bug", "Fix Laravel bug");
    expect(s.startsWith("Title: Fix Laravel bug\nDescription: Use when the user wants to: Fix Laravel bug.")).toBe(true);
    expect(s).toMatch(/Instructions \(\d+\/8000 chars\):\nAct as a Laravel expert\.\nFix the bug\./);
    expect(buildSnippet("perplexity", body, "Fix Laravel bug", "Fix Laravel bug")).toBe(s);
    const long = perplexityProjectFields("x".repeat(9000), "T".repeat(80), "g".repeat(2000));
    expect(long.title.length).toBe(50);
    expect(long.description.length).toBe(1000);
    expect(long.instructions.length).toBe(8000);
  });
});
