// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from "vitest";
import { cleanup, render, screen, fireEvent, waitFor } from "@testing-library/react";

afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.resetModules(); });

async function mount(responses: { config: unknown; run?: unknown }, kind: "text" | "image" | "video" = "text") {
  vi.stubGlobal("fetch", vi.fn(async (_u: string, init?: RequestInit) => new Response(JSON.stringify(init?.method === "POST" ? responses.run : responses.config), { status: 200 })));
  const { RunButton } = await import("@/components/RunButton");
  render(<RunButton text="Write a Diwali caption" kind={kind} />);
}
const cfg = (on: boolean) => ({ available: { text: on, image: on }, turnstileSiteKey: null, limits: { text: 5, image: 1 }, tier: "anon", providers: on ? ["Groq"] : [] });

describe("RunButton", () => {
  it("shows coming soon when no provider is configured", async () => {
    await mount({ config: cfg(false) });
    expect(await screen.findByTestId("run-coming-soon")).toBeTruthy();
    expect(screen.getByRole("button", { name: /coming soon/i })).toHaveProperty("disabled", true);
  });
  it("runs and shows labelled result + privacy note", async () => {
    await mount({ config: cfg(true), run: { ok: true, kind: "text", text: "Shubh Diwali!", provider: "Groq", model: "m", label: "Groq · m", remaining: 4, tier: "anon" } });
    expect(await screen.findByText(/prompt is sent to Groq/)).toBeTruthy();
    fireEvent.click(screen.getByRole("button", { name: "Run free" }));
    await waitFor(() => expect(screen.getByTestId("run-result")).toBeTruthy());
    expect(screen.getByText(/Generated by Groq · m/)).toBeTruthy();
    expect(screen.getByText("Shubh Diwali!")).toBeTruthy();
  });
  it("quota exhausted shows Hinglish message and fallbacks", async () => {
    await mount({ config: cfg(true), run: { ok: false, code: "QUOTA", message: "x" } });
    fireEvent.click(await screen.findByRole("button", { name: "Run free" }));
    const box = await screen.findByTestId("run-quota");
    expect(box.textContent).toContain("Aaj ka free quota khatam");
    expect(box.textContent).toContain("Try in ChatGPT");
    expect(box.textContent).toContain("own API key");
  });
  it("video never offers Run", async () => {
    await mount({ config: cfg(true) }, "video");
    expect(screen.queryByRole("button", { name: /Run free/ })).toBeNull();
    expect(screen.getByText(/Video can.t be generated here/)).toBeTruthy();
  });
});
